#!/usr/bin/env bun
/**
 * menagerie forge — custom-agent generator.
 *
 * Pipeline (OpenAI-compatible image endpoint; grabs omp's provider by default):
 *   1. resolve endowment (IMAGES_API_URL/IMAGES_API_KEY env, else first
 *      provider block in ~/.omp/agent/models.yml — see src/vendor-omp/)
 *   2. POST /v1/images/generations with { model, prompt, n, size }
 *   3. write assets/<name>/map.png + agent.json (clippy.js-compatible) +
 *      appears with a default animation map + README block
 *
 * Sprite slicing: clippy.js expects grids of frames; the generated map.png is
 * delivered as a raw sprite sheet; slice per-agent rows with any editor, then
 * adjust agent.json frames (or use the web HUD's --agent custom for now).
 *
 * Usage:
 *   menagerie forge --prompt "a chibi steelwing raven mascot, game sprite sheet, transparent bg"
 *   menagerie forge --prompt "..." --grid 4x4 --model diffusiongemma
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv, requireOpenAICompat } from '../src/cli/env.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const name = (prompt) =>
	prompt
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '')
		.slice(0, 24) || 'custom-agent';

/** Call an OpenAI-compatible /v1/images/generations endpoint (key optional). */
async function generateImage(endpoint, apiKey, prompt, model, size) {
	const url = endpoint.replace(/\/+$/, '') + '/v1/images/generations';
	const headers = { 'content-type': 'application/json' };
	if (apiKey) headers.authorization = `Bearer ${apiKey}`;
	const res = await fetch(url, {
		method: 'POST',
		headers,
		body: JSON.stringify({ model, prompt, n: 1, size }),
	});
	if (!res.ok) {
		const text = await res.text().catch(() => '');
		throw new Error(`image endpoint ${res.status}: ${text.slice(0, 200)}`);
	}
	const data = await res.json();
	const b64 = data?.data?.[0]?.b64_json;
	const imgUrl = data?.data?.[0]?.url;
	if (b64) return Buffer.from(b64, 'base64');
	if (imgUrl) {
		const img = await fetch(imgUrl);
		if (!img.ok) throw new Error(`image fetch failed: ${img.status}`);
		return Buffer.from(await img.arrayBuffer());
	}
	throw new Error('image endpoint returned no data');
}

/** Fast path: llm4free direct client. Proven lane first (NoLoginTool/flux), auto as fallback. */
async function generateFast(prompt, outPath) {
	const py = 'C:/Users/beebe/AppData/Local/Programs/Python/Python313/python.exe';
	const script = `
import base64, urllib.request
from llm4free.client import Client
c = Client()
out = r'${outPath.replace(/\\/g, '\\\\')}'
def grab(r):
    img = r.data[0]
    b64 = getattr(img, 'b64_json', None)
    url = getattr(img, 'url', None)
    if b64: open(out, 'wb').write(base64.b64decode(b64))
    elif url: urllib.request.urlretrieve(url, out)
    return bool(img)
try:
    print('OK' if grab(c.images.generate(prompt=${JSON.stringify(prompt)})) else 'EMPTY')
except Exception as e:
    print('FAIL ' + repr(e)[:120])
`;
	const { spawnSync } = await import('node:child_process');
	const r = spawnSync(py, ['-c', script], { encoding: 'utf8', timeout: 100_000 });
	if (r.status !== 0) throw new Error('llm4free fast lane failed: ' + (r.stderr || '').slice(0, 140));
	const line = r.stdout.trim().split('\n').pop();
	if (line !== 'OK') throw new Error('llm4free fast lane: ' + line);
}

export async function main(args = {}) {
	loadEnv();
	const prompt = args.prompt || process.env.FORGE_PROMPT;
	if (!prompt) {
		console.error('menagerie forge: --prompt required');
		process.exit(1);
	}
	const grid = args.grid || '4x4';
	const model = args.model || process.env.FORGE_MODEL || 'diffusiongemma';
	const size = args.size || process.env.FORGE_SIZE || '1024x1024';

	const ep = requireOpenAICompat();
	const agentName = name(prompt);
	const dir = join(root, 'assets', 'agents', agentName);
	mkdirSync(dir, { recursive: true });
	const pngPath = join(dir, 'map.png');

	if (args.lib || !ep || /127\.0\.0\.1:8010|localhost:8010/.test(ep.baseUrl || '')) {
		console.log(`[forge] fast lane (llm4free direct client) -> ${pngPath}`);
		await generateFast(prompt, pngPath);
	} else {
		console.log(`[forge] generating '${agentName}' via ${ep.baseUrl} (model=${model})`);
		const png = await generateImage(ep.baseUrl, ep.apiKey, prompt, model, size);
		writeFileSync(pngPath, png);
	}
	if (!existsSync(pngPath) || (await Bun.file(pngPath).size()) < 500) {
		throw new Error('forge: no image produced (fast or http lane)');
	}

	const manifest = {
		name: agentName,
		note: 'generated by menagerie forge — expects a clippy.js-compatible sprite grid',
		grid,
		animations: {
			Idle: [
				[0, 12],
				[1, 12],
			],
			Say: [
				[0, 8],
				[1, 8],
			],
			Wave: [[2, 12]],
			Sad: [[3, 12]],
		},
		map: 'map.png',
		sounds: {},
	};
	const jsonPath = join(dir, 'agent.json');
	writeFileSync(jsonPath, JSON.stringify(manifest, null, 2));
	console.log(`[forge] wrote ${pngPath} (${png.length} bytes) and ${jsonPath}`);
	console.log('[forge] slice frames per grid row, then: menagerie hud --agent ' + agentName);
	return 0;
}

if (existsSync(join(root, 'package.json')) && process.argv[1] === fileURLToPath(import.meta.url)) {
	const { parseArgs } = await import('node:util');
	const { values } = parseArgs({
		args: process.argv.slice(2),
		options: {
			prompt: { type: 'string' },
			grid: { type: 'string' },
			model: { type: 'string' },
			size: { type: 'string' },
			lib: { type: 'boolean' },
		},
	});
	process.exit(await main(values));
}
